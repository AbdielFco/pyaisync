from __future__ import annotations

import tomllib
from pathlib import Path

import pytest
from conftest import write

from pyaisync.cli import main


def run(root: Path, *args: str) -> int:
    return main(["--root", str(root), *args])


def targets(root: Path) -> list[str]:
    data = tomllib.loads((root / ".ai/config.toml").read_text())
    result: list[str] = data["targets"]
    return result


CONFIG = """\
# my comment
version = 1
targets = ["cursor"]   # only cursor for now

[features]
hooks = false

[plugin]
name = "my-tools"
"""


def test_add_and_remove_keep_comments_tables_and_other_keys(tmp_path: Path, capsys) -> None:  # type: ignore[no-untyped-def]
    write(tmp_path, ".ai/config.toml", CONFIG)
    assert run(tmp_path, "target", "add", "claude") == 0
    assert "Enabled: claude" in capsys.readouterr().out
    text = (tmp_path / ".ai/config.toml").read_text()
    assert targets(tmp_path) == ["cursor", "claude"]
    assert "# my comment" in text and "[features]" in text and 'name = "my-tools"' in text
    assert "hooks = false" in text
    assert run(tmp_path, "target", "remove", "cursor") == 0
    assert targets(tmp_path) == ["claude"]
    assert "[plugin]" in (tmp_path / ".ai/config.toml").read_text()


def test_add_handles_multiline_missing_and_duplicate(tmp_path: Path, capsys) -> None:  # type: ignore[no-untyped-def]
    write(tmp_path, ".ai/config.toml", 'version = 1\ntargets = [\n  "cursor",\n  "opencode",\n]\n')
    assert run(tmp_path, "target", "add", "claude", "cursor") == 0
    assert "cursor already enabled" in capsys.readouterr().out
    assert targets(tmp_path) == ["cursor", "opencode", "claude"]
    # no `targets` key means "all three": adding changes nothing, removing writes the key
    write(tmp_path, ".ai/config.toml", "version = 1\n\n[features]\nrules = true\n")
    assert run(tmp_path, "target", "add", "opencode") == 0
    assert "targets" not in tomllib.loads((tmp_path / ".ai/config.toml").read_text())
    assert run(tmp_path, "target", "remove", "cursor") == 0
    data = tomllib.loads((tmp_path / ".ai/config.toml").read_text())
    assert data["targets"] == ["claude", "opencode"] and data["features"] == {"rules": True}


def test_add_is_idempotent_and_remove_keeps_at_least_one(tmp_path: Path) -> None:
    write(tmp_path, ".ai/config.toml", 'version = 1\ntargets = ["cursor"]\n')
    before = (tmp_path / ".ai/config.toml").read_text()
    assert run(tmp_path, "target", "add", "cursor") == 0
    assert (tmp_path / ".ai/config.toml").read_text() == before
    assert run(tmp_path, "target", "remove", "cursor") == 2  # would leave nothing enabled
    assert (tmp_path / ".ai/config.toml").read_text() == before
    assert run(tmp_path, "target", "remove", "claude") == 0  # not enabled: just a note


def test_invalid_names_and_missing_config(tmp_path: Path) -> None:
    with pytest.raises(SystemExit):  # argparse rejects unknown tools
        run(tmp_path, "target", "add", "vim")
    assert run(tmp_path, "target", "add", "claude") == 2  # no .ai/config.toml


def test_add_then_generate_creates_the_claude_files(tmp_path: Path, capsys) -> None:  # type: ignore[no-untyped-def]
    (tmp_path / ".cursor").mkdir()
    assert run(tmp_path, "init") == 0
    assert targets(tmp_path) == ["cursor"]
    write(tmp_path, "CLAUDE.md", "# existing\n")
    write(tmp_path, ".ai/rules/r.md", "---\nalways: true\n---\nrule\n")
    capsys.readouterr()
    assert run(tmp_path, "target", "add", "claude") == 0
    out = capsys.readouterr().out
    assert "Found existing claude configuration" in out and "pyaisync import claude" in out
    assert run(tmp_path, "generate", "--adopt") == 0
    assert (tmp_path / "CLAUDE.md").read_text().startswith("<!-- generated by pyaisync")
    assert run(tmp_path, "check") == 0


def test_remove_then_generate_deletes_only_generated_files(tmp_path: Path) -> None:
    write(tmp_path, ".ai/config.toml", 'version = 1\ntargets = ["claude", "cursor"]\n')
    write(tmp_path, ".ai/rules/r.md", "---\nalways: true\n---\nrule\n")
    write(tmp_path, ".cursor/mine.txt", "mine\n")
    assert run(tmp_path, "generate") == 0
    assert (tmp_path / ".cursor/rules/r.mdc").is_file()
    assert run(tmp_path, "target", "remove", "cursor") == 0
    assert run(tmp_path, "generate") == 0
    assert not (tmp_path / ".cursor/rules").exists()
    assert (tmp_path / ".cursor/mine.txt").read_text() == "mine\n"  # not ours: untouched
    assert (tmp_path / "CLAUDE.md").is_file()


def test_list_shows_enabled_tools(tmp_path: Path, capsys) -> None:  # type: ignore[no-untyped-def]
    assert run(tmp_path, "list") == 0
    assert "enabled" not in capsys.readouterr().out  # no .ai/ here
    write(tmp_path, ".ai/config.toml", 'version = 1\ntargets = ["cursor"]\n')
    assert run(tmp_path, "list") == 0
    out = capsys.readouterr().out
    assert "enabled" in out and "target add" in out
    row = {line.split()[0]: line.split()[1] for line in out.splitlines()[1:4]}
    assert row == {"claude": "no", "cursor": "yes", "opencode": "no"}
