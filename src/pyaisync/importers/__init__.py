"""Import native configuration -> .ai/. Reads native files only; writes only to .ai/."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .. import frontmatter
from ..config import AI_DIR
from ..errors import PyAisyncError
from ..model import NAME_RE
from ..safefs import atomic_write, read_text, read_tree, safe_join
from ..targets.base import GENERATED_MARK

_HEADER_RE = re.compile(r"^<!--\s*generated by pyaisync[^>]*-->\s*\n?", re.MULTILINE)


@dataclass
class ImportReport:
    written: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


@dataclass
class _Item:
    kind: str  # rules | commands | skills
    name: str
    files: dict[str, bytes]  # path relative to .ai/ -> content


def _slug(raw: str) -> str | None:
    name = re.sub(r"[^a-z0-9._-]+", "-", raw.lower()).strip("-.")
    return name if NAME_RE.fullmatch(name) and ".." not in name else None


def _rule_item(name: str, meta: dict[str, Any], body: str) -> _Item:
    out: dict[str, Any] = {}
    if isinstance(meta.get("description"), str) and meta["description"]:
        out["description"] = meta["description"]
    globs = meta.get("globs")
    if isinstance(globs, str):
        globs = [g.strip() for g in globs.split(",") if g.strip()]
    if isinstance(globs, list) and globs:
        out["globs"] = [str(g) for g in globs]
    if meta.get("always") is True or meta.get("alwaysApply") is True:
        out["always"] = True
    text = frontmatter.dump(out, body.strip("\n"))
    return _Item("rules", name, {f"rules/{name}.md": text.encode()})


def _command_item(name: str, meta: dict[str, Any], body: str) -> _Item:
    out = (
        {"description": meta["description"]}
        if isinstance(meta.get("description"), str) and meta["description"]
        else {}
    )
    text = frontmatter.dump(out, body.strip("\n"))
    return _Item("commands", name, {f"commands/{name}.md": text.encode()})


def _read_native(path: Path, rep: ImportReport) -> tuple[dict[str, Any], str] | None:
    try:
        raw = read_text(path)
    except PyAisyncError as exc:
        rep.warnings.append(str(exc))
        return None
    if GENERATED_MARK in raw:
        rep.skipped.append(f"{path.name}: was already generated by pyaisync (skipped)")
        return None
    try:
        meta, body = frontmatter.parse(raw, str(path))
    except PyAisyncError as exc:
        rep.warnings.append(str(exc))
        return None
    return meta, _HEADER_RE.sub("", body)


def _collect_md(directory: Path, suffix: str, kind: str, rep: ImportReport) -> list[_Item]:
    items: list[_Item] = []
    if not directory.is_dir() or directory.is_symlink():
        return items
    for p in sorted(directory.iterdir()):
        if p.suffix != suffix or p.is_symlink() or not p.is_file():
            continue
        name = _slug(p.stem)
        if name is None:
            rep.warnings.append(f"{p.name}: invalid name, not imported")
            continue
        parsed = _read_native(p, rep)
        if parsed is None:
            continue
        meta, body = parsed
        items.append(
            _rule_item(name, meta, body) if kind == "rules" else _command_item(name, meta, body)
        )
    return items


def _collect_skills(directory: Path, rep: ImportReport) -> list[_Item]:
    items: list[_Item] = []
    if not directory.is_dir() or directory.is_symlink():
        return items
    for d in sorted(directory.iterdir()):
        if d.name.startswith(".") or d.is_symlink() or not (d / "SKILL.md").is_file():
            continue
        name = _slug(d.name)
        if name is None:
            rep.warnings.append(f"{d.name}: invalid skill name, not imported")
            continue
        try:
            tree = read_tree(d)
        except PyAisyncError as exc:
            rep.warnings.append(str(exc))
            continue
        items.append(_Item("skills", name, {f"skills/{name}/{r}": b for r, b in tree.items()}))
    return items


def _root_rule(path: Path, rep: ImportReport) -> list[_Item]:
    if not path.is_file() or path.is_symlink():
        return []
    parsed = _read_native(path, rep)
    if parsed is None:
        return []
    meta, body = parsed
    meta = {"always": True, "description": meta.get("description", "")}
    return [_rule_item("project", meta, body)]


def _discover(root: Path, target: str, rep: ImportReport) -> list[_Item]:
    if target == "claude":
        return (
            _root_rule(root / "CLAUDE.md", rep)
            + _collect_md(root / ".claude/commands", ".md", "commands", rep)
            + _collect_skills(root / ".claude/skills", rep)
        )
    if target == "cursor":
        return (
            _collect_md(root / ".cursor/rules", ".mdc", "rules", rep)
            + _collect_md(root / ".cursor/commands", ".md", "commands", rep)
            + _collect_skills(root / ".cursor/skills", rep)
            + _collect_skills(root / ".agents/skills", rep)
        )
    if target == "opencode":
        return (
            _root_rule(root / "AGENTS.md", rep)
            + _collect_md(root / ".opencode/commands", ".md", "commands", rep)
            + _collect_md(root / ".opencode/command", ".md", "commands", rep)
            + _collect_skills(root / ".opencode/skills", rep)
            + _collect_skills(root / ".agents/skills", rep)
        )
    raise PyAisyncError(f"unknown target: {target}")


_NOT_IMPORTED = {
    "claude": (".mcp.json", ".claude/agents"),
    "cursor": (".cursor/mcp.json", ".cursor/agents"),
    "opencode": ("opencode.json", "opencode.jsonc", ".opencode/agents"),
}


def _note_not_imported(root: Path, target: str, rep: ImportReport) -> None:
    for rel in _NOT_IMPORTED[target]:
        if (root / rel).exists():
            rep.warnings.append(
                f"{rel}: subagents/MCP import is not implemented yet (phase 4); skipped"
            )


def _rename(item: _Item, new: str) -> _Item:
    files = {}
    for rel, data in item.files.items():
        parts = rel.split("/")
        if item.kind == "skills":
            parts[1] = new
        else:
            parts[1] = f"{new}.md"
        files["/".join(parts)] = data
    return _Item(item.kind, new, files)


def import_target(
    root: Path, target: str, *, on_conflict: str = "skip", write: bool = True
) -> ImportReport:
    if on_conflict not in ("skip", "rename", "overwrite"):
        raise PyAisyncError("--on-conflict must be skip, rename or overwrite")
    if not (root / AI_DIR / "config.toml").is_file():
        raise PyAisyncError(".ai/config.toml not found: run 'pyaisync init' first")
    rep = ImportReport()
    items = _discover(root, target, rep)
    _note_not_imported(root, target, rep)
    seen: set[tuple[str, str]] = set()
    for item in items:
        key = (item.kind, item.name)
        if key in seen:  # e.g. a skill duplicated in .cursor/skills and .agents/skills
            continue
        seen.add(key)
        dest_exists = any(safe_join(root, f"{AI_DIR}/{r}").exists() for r in item.files)
        same = dest_exists and all(
            (root / AI_DIR / r).is_file() and (root / AI_DIR / r).read_bytes() == d
            for r, d in item.files.items()
        )
        label = f"{item.kind}/{item.name}"
        if same:
            rep.unchanged.append(label)
            continue
        if dest_exists:
            if on_conflict == "skip":
                rep.skipped.append(
                    f"{label}: already exists in .ai/ (use --on-conflict rename|overwrite)"
                )
                continue
            if on_conflict == "rename":
                new = _slug(f"{item.name}-{target}")
                if new is None or any(
                    safe_join(root, f"{AI_DIR}/{r}").exists() for r in _rename(item, new).files
                ):
                    rep.skipped.append(f"{label}: could not rename without a collision")
                    continue
                item = _rename(item, new)
                label = f"{item.kind}/{item.name}"
        for rel, data in item.files.items():
            if write:
                atomic_write(safe_join(root, f"{AI_DIR}/{rel}"), data)
        rep.written.append(label)
    return rep
