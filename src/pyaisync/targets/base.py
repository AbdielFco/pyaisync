from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Protocol

from ..model import Command, Model, Rule

GENERATED_MARK = "generated by pyaisync"
HEADER = f"<!-- {GENERATED_MARK} from .ai/ - do not edit by hand; run 'pyaisync generate' -->"


@dataclass(frozen=True)
class Output:
    path: str  # relative to the repo root, posix
    content: bytes


@dataclass(frozen=True)
class JsonMerge:
    """Entries pyaisync owns inside a (possibly user-edited) JSON file.

    `entries` are written under `key_path` (e.g. ("mcpServers",)); everything else in the file
    is left untouched.
    """

    path: str
    key_path: tuple[str, ...]
    entries: dict[str, Any]


@dataclass(frozen=True)
class Plan:
    outputs: list[Output]
    warnings: list[str]
    merges: list[JsonMerge] = field(default_factory=list)


class Target(Protocol):
    name: str
    supported: frozenset[str]

    def plan(self, model: Model) -> Plan: ...


def text(path: str, content: str) -> Output:
    return Output(path, content.encode("utf-8"))


def rules_document(rules: tuple[Rule, ...]) -> str:
    """Single document for targets that read one instructions file (CLAUDE.md/AGENTS.md)."""
    parts = [HEADER, ""]
    ordered = sorted(rules, key=lambda r: (not r.always, r.name))
    for r in ordered:
        parts.append(f"## {r.name}")
        if r.globs and not r.always:
            parts.append(f"_Applies to: {', '.join(f'`{g}`' for g in r.globs)}_")
        elif r.description and not r.always:
            parts.append(f"_When: {r.description}_")
        parts += ["", r.body.strip("\n"), ""]
    return "\n".join(parts).rstrip("\n") + "\n"


def command_meta(c: Command) -> dict[str, str]:
    return {"description": c.description} if c.description else {}
